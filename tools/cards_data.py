# Starter question bank for Roadmap Lab.
# Each card: id, topic, type ("mcq" starts as multiple choice and becomes a flashcard
# after 2 correct answers; "flashcard" is recall-only), prompt, options (mcq: the correct
# answer must be one of them; wrong options are real common mistakes), answer,
# explanation, unlockedBy (the roadmap task that teaches it).
# Fake data only: Ravi Traders, Mohan and Sita are invented.

def mcq(id, topic, unlocked_by, prompt, answer, wrong, explanation):
    return dict(id=id, topic=topic, type="mcq", prompt=prompt, options=[answer] + list(wrong),
                answer=answer, explanation=explanation, unlockedBy=unlocked_by)

def flash(id, topic, unlocked_by, prompt, answer, explanation):
    return dict(id=id, topic=topic, type="flashcard", prompt=prompt, options=[], answer=answer,
                explanation=explanation, unlockedBy=unlocked_by)

